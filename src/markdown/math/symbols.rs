/// 命令（不带反斜杠）换成的符号；不认得的是空的。
pub fn symbol(name: &str) -> Option<&'static str> {
    SYMBOLS
        .iter()
        .find(|(known, _)| *known == name)
        .map(|(_, symbol)| *symbol)
}

